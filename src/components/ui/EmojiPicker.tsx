interface EmojiPickerProps {
  onSelect: (emoji: string) => void
}

export function EmojiPicker({ onSelect }: EmojiPickerProps) {
  const [activeGroup, setActiveGroup] = useState<keyof typeof emojiGroups>("😊")

  const groupNames: Record<string, string> = {
    "😊": "Smileys",
    "👍": "Gestures",
    "❤️": "Hearts & Symbols",
    "✨": "Stars & Weather",
    "🐶": "Animals",
    "🍎": "Food & Drinks",
    "⚽": "Sports & Activities",
    "🚗": "Travel & Transport",
    "🏠": "Places & Buildings",
    "📱": "Technology",
    "🎂": "Events & Celebrations",
    "🌍": "Nature & World"
  }

  return (
    <div className="bg-white border border-gray-300 rounded-lg shadow-lg p-3 w-80 max-h-96 flex flex-col">
      {/* Tab buttons */}
      <div className="flex flex-wrap justify-start mb-2 gap-1 overflow-x-auto pb-1">
        {Object.keys(emojiGroups).map(group => (
          <button
            key={group}
            type="button"
            className={`px-2 py-1 rounded-md text-lg flex-shrink-0 transition-colors ${
              activeGroup === group ? "bg-blue-100 text-blue-700" : "text-gray-600 hover:bg-gray-100"
            }`}
            onClick={() => setActiveGroup(group as keyof typeof emojiGroups)}
            title={groupNames[group]}
          >
            {group}
          </button>
        ))}
      </div>

      {/* Emoji grid */}
      <div className="grid grid-cols-8 gap-1 max-h-64 overflow-y-auto">
        {emojiGroups[activeGroup].map((emoji, idx) => (
          <button
            key={`${emoji}-${idx}`}
            type="button"
            className="text-xl hover:bg-blue-100 rounded-md p-1.5 transition-colors focus:outline-none focus:ring-2 focus:ring-blue-400"
            onClick={() => onSelect(emoji)}
            aria-label={`Insert emoji ${emoji}`}
          >
            {emoji}
          </button>
        ))}
      </div>
    </div>
  )
}
